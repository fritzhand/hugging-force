#!/usr/bin/env node
/* Builds the design tokens (design/hugging-force.tokens.json, DTCG 2025.10 format) into
   - src/styles/tokens.css: one CSS custom property per token (--color-hf-yellow, --space-4, ...);
   - src/design/tokens.ts: every color as a CSS color string, for the 3D scene.
   Aliases ("{color.hf.yellow}") are resolved. `--check` writes nothing and fails when either file
   is out of date (it runs before every build). */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const SOURCE = "design/hugging-force.tokens.json";
const CSS = "src/styles/tokens.css";
const TS = "src/design/tokens.ts";
const check = process.argv.includes("--check");

const doc = JSON.parse(await readFile(`${root}${SOURCE}`, "utf8"));

/** Every token as { path, type, value }, with group types inherited. */
function collect(node, path = [], inherited = undefined, out = []) {
  const type = node.$type ?? inherited;
  if ("$value" in node) {
    out.push({ path, type, value: node.$value });
    return out;
  }
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$") || typeof v !== "object" || v === null) continue;
    collect(v, [...path, k], type, out);
  }
  return out;
}

const tokens = collect(doc);
const byPath = new Map(tokens.map((t) => [t.path.join("."), t]));

function resolve(token, seen = new Set()) {
  if (typeof token.value === "string" && /^\{[^}]+\}$/.test(token.value)) {
    const ref = token.value.slice(1, -1);
    if (seen.has(ref)) throw new Error(`alias loop at ${ref}`);
    const target = byPath.get(ref);
    if (!target) throw new Error(`${token.path.join(".")} refers to missing ${ref}`);
    seen.add(ref);
    return { ...resolve(target, seen), path: token.path };
  }
  return token;
}

const round = (n, d = 4) => Number(n.toFixed(d));

function color(v) {
  if (v.colorSpace !== "srgb" || v.components.length !== 3) throw new Error(`only sRGB colors are supported: ${JSON.stringify(v)}`);
  const alpha = v.alpha ?? 1;
  const hex = `#${v.components.map((c) => Math.round(c * 255).toString(16).padStart(2, "0")).join("")}`;
  if (v.hex && v.hex.toLowerCase() !== hex) throw new Error(`hex ${v.hex} does not match components (${hex})`);
  if (alpha >= 1) return hex;
  const [r, g, b] = v.components.map((c) => Math.round(c * 255));
  return `rgb(${r} ${g} ${b} / ${round(alpha, 3)})`;
}

const dim = (v) => `${v.value}${v.unit}`;

function css(token) {
  const { type, value } = resolve(token);
  switch (type) {
    case "color":
      return color(value);
    case "dimension":
    case "duration":
      return dim(value);
    case "fontFamily":
      return (Array.isArray(value) ? value : [value]).map((f) => (/^[a-z-]+$/.test(f) ? f : `"${f}"`)).join(", ");
    case "fontWeight":
      return String(value);
    case "cubicBezier":
      return `cubic-bezier(${value.join(", ")})`;
    case "shadow":
      return (Array.isArray(value) ? value : [value]).map((s) => `${dim(s.offsetX)} ${dim(s.offsetY)} ${dim(s.blur)} ${dim(s.spread)} ${color(s.color)}`).join(", ");
    default:
      throw new Error(`${token.path.join(".")}: unsupported type ${type}`);
  }
}

const name = (path) => `--${path.join("-")}`;

const cssOut = [
  `/* Generated by scripts/build-tokens.mjs from ${SOURCE}. Do not edit: change the tokens and run npm run tokens. */`,
  ":root {",
  "  color-scheme: dark;",
  ...tokens.map((t) => `  ${name(t.path)}: ${css(t)};`),
  "}",
  "",
].join("\n");

const colors = {};
for (const t of tokens) {
  if (resolve(t).type !== "color") continue;
  let node = colors;
  const path = t.path.slice(1);
  for (const k of path.slice(0, -1)) node = node[k] ??= {};
  node[path.at(-1)] = css(t);
}

const tsOut = [
  `/* Generated by scripts/build-tokens.mjs from ${SOURCE}. Do not edit: change the tokens and run npm run tokens. */`,
  "",
  "/** Every color token as a CSS color string (hex, or rgb() with alpha). */",
  `export const COLOR = ${JSON.stringify(colors, null, 2)} as const;`,
  "",
].join("\n");

const outputs = [
  [CSS, cssOut],
  [TS, tsOut],
];

if (check) {
  const stale = [];
  for (const [file, text] of outputs) {
    const now = await readFile(`${root}${file}`, "utf8").catch(() => "");
    if (now !== text) stale.push(file);
  }
  if (stale.length) {
    console.error(`Out of date with ${SOURCE}: ${stale.join(", ")}. Run npm run tokens.`);
    process.exit(1);
  }
  console.log(`tokens ok: ${tokens.length} tokens`);
} else {
  for (const [file, text] of outputs) await writeFile(`${root}${file}`, text);
  console.log(`Wrote ${CSS} and ${TS}: ${tokens.length} tokens`);
}
